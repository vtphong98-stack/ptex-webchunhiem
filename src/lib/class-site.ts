function foldSubject(raw: string) {
  return raw
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/đ/gi, "d")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "");
}

function subjectTone(raw: string) {
  let hash = 0;
  for (const ch of raw) hash = (hash + ch.charCodeAt(0)) % 6;
  return `subject-tone-${hash}`;
}

/**
 * Tên môn chuẩn hoá: file thời khóa biểu của trường viết tắt ("T", "V", "CC"),
 * còn bảng phân công giáo viên lại ghi đủ ("Toán"). Cả hai phải quy về một tên
 * thì tra tên giáo viên mới trúng.
 */
export function canonicalSubject(raw: string) {
  const name = raw.trim() || "-";
  if (name === "-") return "-";
  return SUBJECT_ALIAS[foldSubject(name)] || name;
}

export function subjectStyle(raw: string): TimetableCell {
  const name = raw.trim() || "-";
  if (name === "-") return { subject: "-" };
  const canonical = canonicalSubject(name);
  return {
    // Display the canonical name. The uploaded Excel abbreviates ("T", "V",
    // "CC"), and showing the raw cell made the timetable unreadable even though
    // SUBJECT_ALIAS already knew what each letter meant.
    subject: canonical,
    teacher: SUBJECT_TEACHERS[canonical] || SUBJECT_TEACHERS[name],
    className: SUBJECT_CLASS[canonical] || SUBJECT_CLASS[name] || subjectTone(canonical),
  };
}

/**
 * "Võ Thanh Phong" -> "V.T.Phong".
 *
 * Ô thời khóa biểu trên điện thoại chỉ rộng ~56px, không đủ cho tên đầy đủ.
 * Viết tắt các chữ đệm và giữ nguyên tên gọi (từ cuối) vẫn nhận ra được thầy cô
 * nào mà chỉ chiếm khoảng một nửa bề rộng.
 */
export function shortTeacherName(full?: string) {
  if (!full) return "";
  const parts = full.trim().split(/\s+/).filter(Boolean);
  if (parts.length <= 1) return parts[0] ?? "";
  const given = parts[parts.length - 1];
  const initials = parts.slice(0, -1).map((word) => `${word[0].toUpperCase()}.`).join("");
  return `${initials}${given}`;
}

